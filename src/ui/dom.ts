export function icon(name: keyof typeof P | string, size = 20): SVGSVGElement {
  const wrap = document.createElement("span");
  wrap.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] ?? ""}</svg>`;
  return wrap.firstElementChild as SVGSVGElement;
}

export function iconBtn(name: string, label: string, onclick: (e: MouseEvent) => void, extra = ""): HTMLButtonElement {
  const b = h("button", { class: `ibtn ${extra}`, title: label, "aria-label": label, type: "button", onclick });
  b.append(icon(name));
  return b;
}

export function fmtDuration(ms: number) {
  const s = Math.floor(ms / 1000);
  const hh = Math.floor(s / 3600), mm = Math.floor((s % 3600) / 60), ss = s % 60;
  const p = (n: number) => String(n).padStart(2, "0");
  return hh ? `${hh}:${p(mm)}:${p(ss)}` : `${p(mm)}:${p(ss)}`;
}
